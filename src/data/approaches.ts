/** Try to find an approach by tag string — handles partial matches */
export const findApproach = (tag: string): ApproachInfo | undefined => {
  if (approaches[tag]) return approaches[tag];
  const lower = tag.toLowerCase();
  return Object.values(approaches).find(
    (a) => a.id.toLowerCase() === lower || a.name.includes(tag)
  );
};
